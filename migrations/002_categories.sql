-- Миграция 2: категории (фильмы, сериалы, аниме и т.д.).
--
-- Категория хранится прямо в фильме. Список доступных категорий строится
-- из предопределённых значений и уже сохранённых записей, поэтому
-- пользователь может добавлять свои категории без отдельной таблицы.
ALTER TABLE films ADD COLUMN category TEXT NOT NULL DEFAULT 'Фильмы';

CREATE INDEX idx_films_category ON films (category);
